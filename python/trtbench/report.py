"""Render README tables from harness JSON, so no number is typed by hand.

    python -m trtbench.report results/<run>/phase1_latency.json [more.json ...]
    python -m trtbench.report results/<run>/self_test.json

Rejected results are listed with the reason and without their numbers: a
measurement the harness refused is not a result.
"""

from __future__ import annotations

import json
import sys
from typing import Any, Dict, List, Optional

from .results import validate_report


def _cuda(v: int) -> str:
    return f"{v // 1000}.{(v % 1000) // 10}" if isinstance(v, int) and v > 0 else "?"


def environment_line(env: Dict[str, Any], clocks_locked: Optional[bool] = None) -> str:
    """One line stating everything needed to reproduce or reject the numbers."""
    parts = [
        f"{env['gpu_name']} (sm_{env['compute_capability'].replace('.', '')}, {env['sm_count']} SMs)",
        f"driver {env['driver_version'] or '?'}",
        f"CUDA runtime {_cuda(env['cuda_runtime_version'])}",
        f"ECC {'on' if env['ecc_enabled'] == 1 else 'off' if env['ecc_enabled'] == 0 else '?'}",
        f"persistence {'on' if env['persistence_mode'] == 1 else 'off' if env['persistence_mode'] == 0 else '?'}",
        f"power limit {env['power_limit_w']:.0f} W" if env["power_limit_w"] > 0 else "power limit ?",
    ]
    if clocks_locked is not None:
        parts.append("clocks locked" if clocks_locked else "clocks unlocked")
    parts.append(f"trtbench {env['git_sha']}")
    parts.append(env["timestamp_utc"])
    return ", ".join(parts)


def _us(ms: float) -> str:
    return f"{ms * 1e3:,.2f}"


def _flags(r: Dict[str, Any], severity: str) -> List[str]:
    return [f["flag"] for f in r["findings"] if f["severity"] == severity]


def _achieved(r: Dict[str, Any]) -> str:
    rf = r["roofline"]
    if rf["bound"] == "memory":
        return f"{rf['achieved_gbps']:.1f} GB/s ({rf['pct_bw_theoretical']:.1f}% of theoretical)"
    if rf["bound"] == "compute":
        return (f"{rf['achieved_gflops']:,.0f} GFLOP/s ({rf['pct_compute_peak']:.1f}% of peak "
                f"at run clock)")
    return "-"


def results_table(report: Dict[str, Any]) -> str:
    validate_report(report)
    rows = [
        "| Workload | Mode | Samples | Device p50 (µs) | Device p99 (µs) | Host enqueue p50 (µs) "
        "| Achieved | SM clock (MHz) | Verdict |",
        "|---|---|---:|---:|---:|---:|---|---|---|",
    ]
    for r in report["results"]:
        c = r["clocks"]
        clk = f"{c['sm_mhz']['min']}–{c['sm_mhz']['max']}" if c.get("available") else "?"
        mode, n = r["config"]["mode"], r["device_ms"]["n"]
        if not r["trustworthy"]:
            rows.append(f"| {r['name']} | {mode} | {n} | – | – | – | – | {clk} "
                        f"| **rejected**: {', '.join(_flags(r, 'invalid'))} |")
            continue
        warn = _flags(r, "warning")
        verdict = "accepted" + (f" ({', '.join(warn)})" if warn else "")
        d, h = r["device_ms"], r["host_enqueue_ms"]
        rows.append(f"| {r['name']} | {mode} | {n} | {_us(d['p50'])} | {_us(d['p99'])} "
                    f"| {_us(h['p50'])} | {_achieved(r)} | {clk} | {verdict} |")
    return "\n".join(rows)


def self_test_table(st: Dict[str, Any]) -> str:
    rows = ["| ID | Layer | Trap | Result | Wrong benchmark | Control |",
            "|---|---|---|---|---|---|"]
    for t in st["traps"]:
        rows.append(f"| {t['id']} | {t['layer']} | {t['name']} | {t['outcome']} "
                    f"| {t['wrong']} | {t['control']} |")
    return "\n".join(rows)


def render(doc: Dict[str, Any]) -> str:
    if "traps" in doc:
        head = environment_line(doc["environment"]) if doc.get("environment") else "no device"
        return f"{head}\n\n{self_test_table(doc)}"
    locked = all(r["clocks"].get("locked") for r in doc["results"]) if doc["results"] else None
    return f"{environment_line(doc['environment'], locked)}\n\n{results_table(doc)}"


def main(argv: Optional[List[str]] = None) -> int:
    paths = sys.argv[1:] if argv is None else argv
    if paths and paths[0] == "--phase2":
        if len(paths) != 3:
            print("usage: python -m trtbench.report --phase2 REPORT.json ACCURACY.json",
                  file=sys.stderr)
            return 2
        with open(paths[1], encoding="utf-8") as f:
            rep = json.load(f)
        with open(paths[2], encoding="utf-8") as f:
            acc = json.load(f)
        print(f"<!-- generated by python -m trtbench.report --phase2 {paths[1]} {paths[2]} -->")
        print(environment_line(rep["environment"]))
        print()
        print(phase2_tables(rep, acc))
        return 0
    if not paths:
        print(__doc__, file=sys.stderr)
        return 2
    for p in paths:
        with open(p, encoding="utf-8") as f:
            print(f"<!-- generated by python -m trtbench.report {p} -->")
            print(render(json.load(f)))
            print()
    return 0


if __name__ == "__main__":
    sys.exit(main())


# --------------------------------------------------------------------------- phase 2

_BACKEND_ORDER = {"torch_eager": 0, "onnxruntime": 1, "tensorrt": 2, "tensorrt+graph": 3}
_PREC_ORDER = {"fp32": 0, "fp16": 1, "int8": 2}
_METRIC_LABEL = {"top1_pct": "top-1 %", "cosine_vs_fp32": "cosine vs FP32", "perplexity": "perplexity"}


def _acc_key(r: Dict[str, Any]) -> str:
    """Accuracy belongs to the engine, so a graph replay shares its engine's."""
    return r["name"].replace("+graph", "")


def _fmt_acc(entry: Optional[Dict[str, Any]]) -> str:
    if not entry:
        return "–"
    v = entry["value"]
    return f"{v:.2f}" if entry["metric"] != "cosine_vs_fp32" else f"{v:.6f}"


def _speedup_cell(base, r, acc: Dict[str, Any]) -> str:
    from .diff import compare_results

    if base is None:
        return "no PyTorch FP32 baseline"
    if r is base:
        return "baseline"
    a_base, a_cand = acc.get(_acc_key(base)), acc.get(_acc_key(r))
    accuracy = None
    if a_base and a_cand:
        accuracy = {"metric": a_base["metric"], "baseline": a_base["value"],
                    "candidate": a_cand["value"]}
    row = compare_results(base, r, accuracy)
    if row.status != "ok":
        return f"{row.status}: {row.reason}"
    cell = f"{row.speedup_p50:.2f}×"
    if accuracy and r["precision"] != base["precision"]:
        d = accuracy["candidate"] - accuracy["baseline"]
        unit = " pts" if accuracy["metric"] == "top1_pct" else ""
        cell += f" (Δ {_METRIC_LABEL[accuracy['metric']]} {d:+.4g}{unit})"
    return cell


def phase2_tables(report: Dict[str, Any], acc: Dict[str, Any]) -> str:
    validate_report(report)
    rows = [r for r in report["results"] if r.get("labels", {}).get("backend") in _BACKEND_ORDER]
    groups: Dict[tuple, List[Dict[str, Any]]] = {}
    for r in rows:
        lb = r["labels"]
        groups.setdefault((lb["model"], int(lb["batch"])), []).append(r)

    out: List[str] = []
    for (model, batch) in sorted(groups):
        rs = sorted(groups[(model, batch)], key=lambda r: (
            _BACKEND_ORDER[r["labels"]["backend"]], _PREC_ORDER.get(r["labels"]["precision"], 9)))
        base = next((r for r in rs if r["labels"]["backend"] == "torch_eager"
                     and r["labels"]["precision"] == "fp32"), None)
        metric = next((acc[_acc_key(r)]["metric"] for r in rs if _acc_key(r) in acc), None)
        out.append(f"#### {model}, batch {batch}\n")
        out.append(f"| Backend | Precision | p50 (ms) | p99 (ms) | Throughput (inf/s) "
                   f"| DRAM GB/s (lower bound) | {_METRIC_LABEL.get(metric, 'accuracy')} "
                   f"| vs PyTorch FP32 (p50) | Verdict |")
        out.append("|---|---|---:|---:|---:|---:|---:|---|---|")
        for r in rs:
            lb = r["labels"]
            a = acc.get(_acc_key(r))
            if not r["trustworthy"]:
                out.append(f"| {lb['backend']} | {lb['precision']} | – | – | – | – | {_fmt_acc(a)} "
                           f"| – | **rejected**: {', '.join(_flags(r, 'invalid'))} |")
                continue
            d = r["device_ms"]
            warn = _flags(r, "warning")
            out.append(
                f"| {lb['backend']} | {lb['precision']} | {d['p50']:.3f} | {d['p99']:.3f} "
                f"| {batch * 1e3 / d['p50']:,.1f} | {r['roofline']['achieved_gbps']:.1f} "
                f"| {_fmt_acc(a)} | {_speedup_cell(base, r, acc)} "
                f"| accepted{(' (' + ', '.join(warn) + ')') if warn else ''} |")
        out.append("")

    out.append("#### CUDA graphs: same engine, launched as one graph\n")
    out.append("| Model | Batch | Precision | Device p50, enqueueV3 (ms) | Device p50, graph (ms) "
               "| Device Δ | Host enqueue p50, enqueueV3 (µs) | Host enqueue p50, graph (µs) |")
    out.append("|---|---:|---|---:|---:|---:|---:|---:|")
    by_name = {r["name"]: r for r in rows}
    for r in sorted(rows, key=lambda r: r["name"]):
        if r["labels"]["backend"] != "tensorrt":
            continue
        g = by_name.get(r["name"] + "+graph")
        if g is None:
            continue
        lb = r["labels"]
        if not (r["trustworthy"] and g["trustworthy"]):
            out.append(f"| {lb['model']} | {lb['batch']} | {lb['precision']} | – | – "
                       f"| not compared: a side was rejected | – | – |")
            continue
        a, b = r["device_ms"]["p50"], g["device_ms"]["p50"]
        out.append(f"| {lb['model']} | {lb['batch']} | {lb['precision']} | {a:.3f} | {b:.3f} "
                   f"| {100 * (b - a) / a:+.1f}% | {r['host_enqueue_ms']['p50'] * 1e3:.1f} "
                   f"| {g['host_enqueue_ms']['p50'] * 1e3:.1f} |")
    return "\n".join(out)
